RSpec.describe Caracal::Md::Svg do
  def svg(body, attributes = 'width="100" height="50"')
    %(<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" #{attributes}>#{body}</svg>)
  end

  def clean(markup)
    described_class.clean(markup)
  end

  def refused(markup)
    expect { clean(markup) }.to raise_error(described_class::Error)
  end

  it 'recognizes SVG documents' do
    expect(described_class.svg?(svg(''))).to be(true)
    expect(described_class.svg?(%(\xEF\xBB\xBF<?xml version="1.0"?>\n<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "x.dtd">\n<!-- made -->\n<svg/>))).to be(true)
    expect(described_class.svg?('<html><svg/></html>')).to be(false)
    expect(described_class.svg?(png)).to be(false)
    expect(described_class.svg?(nil)).to be(false)
  end

  it 'keeps what diagram tools write and drops their DOCTYPE and comments' do
    markup = <<~SVG
      <?xml version="1.0" encoding="UTF-8" standalone="no"?>
      <!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
      <!-- Generated by graphviz -->
      #{svg('<g id="graph0" class="graph" transform="translate(4 40)"><title>G</title><ellipse fill="none" stroke="black" cx="27" cy="-18" rx="27" ry="18"/><text text-anchor="middle" x="27" y="-13.8" font-family="Times,serif" font-size="14.00">a</text></g>', 'width="152pt" height="44pt" viewBox="0 0 152 44"')}
    SVG
    result = clean(markup)
    expect(result.removed).to be_empty
    expect(result.svg).not_to include('DOCTYPE', 'graphviz')
    expect(result.svg).to include('<ellipse fill="none"', 'font-family="Times,serif"', '<title>G</title>')
    expect([result.width, result.height]).to eq([152.0, 44.0])
  end

  it 'refuses entity declarations and internal DTDs' do
    refused(%(<!DOCTYPE svg [<!ENTITY a "aaaaaaaaaa"><!ENTITY b "&a;&a;&a;&a;&a;">]>#{svg('<text>&b;</text>')}))
    refused(%(<!DOCTYPE svg [<!ENTITY x SYSTEM "file:///etc/passwd">]>#{svg('<text>&x;</text>')}))
    refused(%(<!DOCTYPE svg SYSTEM "http://example.com/x.dtd" [ ]>#{svg('')}))
  end

  it 'refuses what is not a well-formed, UTF-8 SVG document' do
    refused(svg('<g>'))
    refused(svg('<text>&nbsp;</text>'))
    refused("<svg xmlns=\"http://www.w3.org/2000/svg\"><text>\xFF</text></svg>".b)
    refused('<html xmlns="http://www.w3.org/1999/xhtml"/>')
    refused('<svg width="10" height="10"/>')
  end

  it 'removes scripts, event handlers, foreign content and animation' do
    result = clean(svg(<<~BODY))
      <script>alert(1)</script>
      <rect width="10" height="10" onclick="alert(1)" onmouseover="x()"/>
      <foreignObject><div xmlns="http://www.w3.org/1999/xhtml"><script>alert(2)</script></div></foreignObject>
      <a xlink:href="#x"><set attributeName="href" to="javascript:alert(3)"/><animate attributeName="xlink:href" values="javascript:alert(4)"/></a>
    BODY
    expect(result.svg).not_to match(/script|alert|onclick|onmouseover|foreignObject|<set|<animate/)
    expect(result.removed).to eq(%w[animate foreignObject onclick onmouseover script set])
    expect(result.svg).to include('<rect width="10" height="10"/>')
  end

  it 'keeps #id references and inline PNG, drops every other reference' do
    data_png = "data:image/png;base64,#{[png].pack('m0')}"
    result = clean(svg(<<~BODY))
      <defs><circle id="dot" r="2"/></defs>
      <use xlink:href="#dot"/>
      <use href="#dot"/>
      <image xlink:href="#{data_png}" width="10" height="10"/>
      <image xlink:href="file:///etc/secret.png" width="10" height="10"/>
      <image href="http://example.com/track.png" width="10" height="10"/>
      <image href="secret.png" width="10" height="10"/>
      <image href="data:text/html;base64,PHNjcmlwdD4=" width="10" height="10"/>
      <use xlink:href="other.svg#x"/>
      <a href="javascript:alert(1)"><text>link</text></a>
      <a href="https://example.com"><text>out</text></a>
      <g xml:base="http://example.com/"/>
    BODY
    expect(result.svg.scan('<use').size).to eq(2)
    expect(result.svg.scan('<image').size).to eq(1)
    expect(result.svg).to include(data_png, '<text>link</text>', '<text>out</text>')
    expect(result.svg).not_to match(/file:|example\.com|javascript:|secret|text\/html|other\.svg|xml:base/)
    expect(result.removed).to eq(['external references'])
  end

  it 'drops CSS that loads anything' do
    result = clean(svg(<<~BODY))
      <style>@import url(http://example.com/x.css); rect { fill: red }</style>
      <style>rect { stroke: blue }</style>
      <linearGradient id="g"><stop offset="0" stop-color="red"/></linearGradient>
      <rect width="1" height="1" fill="url(#g)" style="fill: url('#g'); stroke: url(http://example.com/p.svg#x); opacity: 0.5"/>
      <rect width="1" height="1" fill="url(http://example.com/x)" filter="u\\72l(http://example.com/f)"/>
      <rect width="1" height="1" style="background: image-set('http://example.com/a.png' 1x)"/>
    BODY
    expect(result.svg).not_to include('example.com', '@import', '\\72')
    expect(result.svg).to include('rect { stroke: blue }', %(fill="url(#g)"), %(style="fill: url('#g'); opacity: 0.5"))
    expect(result.removed).to include('style element loading resources', 'style declarations loading resources',
                                      'fill loading resources', 'filter loading resources')
  end

  it 'drops processing instructions, comments and other namespaces' do
    result = clean(%(<?xml-stylesheet href="http://example.com/x.css"?>) + svg(<<~BODY))
      <!-- note -->
      <?php echo 1 ?>
      <sodipodi:namedview xmlns:sodipodi="http://sodipodi.sourceforge.net/DTD/sodipodi-0.dtd"/>
      <g xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" inkscape:label="Layer 1"><rect width="1" height="1"/></g>
    BODY
    expect(result.svg).not_to match(/stylesheet|note|php|sodipodi:namedview|inkscape:label/)
    expect(result.removed).to be_empty
  end

  it 'refuses reference cycles, exploding <use> trees and too many nodes' do
    refused(svg('<g id="a"><use xlink:href="#a"/></g>'))
    refused(svg('<use id="a" xlink:href="#b"/><use id="b" xlink:href="#a"/>'))

    levels = (1..12).map { |i| %(<g id="l#{i}">#{%(<use xlink:href="#l#{i - 1}"/>) * 10}</g>) }
    bomb = svg(%(<defs><rect id="l0" width="1" height="1"/>#{levels.join}</defs><use xlink:href="#l12"/>))
    expect { clean(bomb) }.to raise_error(described_class::Error, /expands to more than/)

    expect { described_class.clean(svg('<g/>' * 20), max_elements: 10) }.to raise_error(described_class::Error, /more than 10 nodes/)
    expect { described_class.clean(svg(''), max_bytes: 10) }.to raise_error(described_class::Error, /larger than 10 bytes/)
  end

  it 'makes blank PNGs in the proportions of the SVG' do
    expect(Caracal::ImageSize.read(described_class.blank_png(300, 100))).to eq([32, 11])
    expect(Caracal::ImageSize.read(described_class.blank_png(1, 1000))).to eq([1, 32])
  end

  it 'reads the size from width and height, else the viewBox' do
    size = ->(attributes) { clean(svg('', attributes)).then { |c| [c.width.round(2), c.height.round(2)] } }
    expect(size.call('width="2in" height="1in"')).to eq([144.0, 72.0])
    expect(size.call('width="200" height="100"')).to eq([150.0, 75.0])
    expect(size.call('width="10mm" viewBox="0 0 40 20"')).to eq([28.35, 14.17])
    expect(size.call('width="100%" height="100%" viewBox="0 0 400 200"')).to eq([300.0, 150.0])
    expect(size.call('')).to eq([225.0, 112.5])
  end
end

RSpec.describe 'SVG images' do
  let(:markup) { %(<svg xmlns="http://www.w3.org/2000/svg" width="200" height="100"><script>x()</script><rect width="200" height="100"/></svg>) }
  let(:ns) { NS.merge('a' => 'http://schemas.openxmlformats.org/drawingml/2006/main', 'asvg' => 'http://schemas.microsoft.com/office/drawing/2016/SVG/main') }

  def render(markdown, **options)
    @renderer = Caracal::Md::Renderer.new(**options)
    @docx = @renderer.render(markdown)
    document_xml(@docx)
  end

  # The raster and the SVG part of the document's first picture.
  def picture_parts(docx = @docx)
    pkg  = package(docx)
    main = 'word/document.xml'
    blip = pkg.xml(main).at_xpath('//a:blip', ns)
    part = ->(id) { id && pkg[pkg.resolve(main, pkg.relationship(main, id)[:target])] }
    [part.call(blip['r:embed']), part.call(blip.at_xpath('.//asvg:svgBlip/@r:embed', ns)&.value)]
  end

  it 'embeds the cleaned SVG with the rasterized PNG as fallback, at the size of the SVG', if: Caracal::Md::Svg.embeddable? do
    received = nil
    rasterizer = ->(block) { received = block; png(400, 200) }
    doc = render('![Plan](plan.svg)', image_loader: ->(_) { markup }, svg_rasterizer: rasterizer)

    expect(received.language).to eq('svg')
    raster, svg = picture_parts
    expect(raster).to eq(png(400, 200))
    expect(svg).to eq(received.source)
    expect(svg).to include('<rect')
    expect(svg).not_to include('script')
    expect(package(@docx).default_content_type('svg')).to eq('image/svg+xml')
    expect(doc.at_xpath('//wp:extent/@cx', NS).value.to_i).to eq(150 * 12_700)
    expect(@renderer.warnings).to eq(['plan.svg: removed from the SVG: script'])
  end

  it 'falls back to a blank PNG without a rasterizer, or when it fails', if: Caracal::Md::Svg.embeddable? do
    render('![Plan](plan.svg)', image_loader: ->(_) { markup })
    raster, svg = picture_parts
    expect(Caracal::ImageSize.read(raster)).to eq([32, 16])
    expect(svg).to include('<rect')
    expect(@renderer.warnings).to eq(['plan.svg: removed from the SVG: script'])

    render('![Plan](plan.svg)', image_loader: ->(_) { markup }, svg_rasterizer: ->(block) { block.source })
    expect(Caracal::ImageSize.read(picture_parts.first)).to eq([32, 16])
    expect(@renderer.warnings.last).to eq('plan.svg: svg handler returned no PNG, JPEG or GIF image; the fallback image is blank')
  end

  it "shows the rasterizer's PNG alone, or the alt text, with caracal 2.0.0" do
    allow(Caracal::Md::Svg).to receive(:embeddable?).and_return(false)

    render('![Plan](plan.svg)', image_loader: ->(_) { markup }, svg_rasterizer: ->(_) { png(400, 200) })
    expect(picture_parts).to eq([png(400, 200), nil])

    doc = render('![Plan](plan.svg)', image_loader: ->(_) { markup })
    expect(body_text(doc)).to eq('Plan')
    expect(@renderer.warnings.last).to eq('plan.svg: SVG needs an svg_rasterizer, or caracal with SVG support')
  end

  it 'refuses SVG it cannot clean' do
    doc = render('![Bomb](x.svg)', image_loader: ->(_) { %(<!DOCTYPE svg [<!ENTITY a "a">]><svg xmlns="http://www.w3.org/2000/svg"/>) },
                                   svg_rasterizer: ->(_) { png })
    expect(body_text(doc)).to eq('Bomb')
    expect(@renderer.warnings).to eq(['x.svg: SVG refused, it declares entities or an internal DTD'])
  end

  it 'takes SVG from code handlers', if: Caracal::Md::Svg.embeddable? do
    doc = render("```dot\na -> b\n```\n", code_handlers: { 'dot' => ->(_) { markup } })
    expect(picture_parts.last).to include('<rect')

    allow(Caracal::Md::Svg).to receive(:embeddable?).and_return(false)
    doc = render("```dot\na -> b\n```\n", code_handlers: { 'dot' => ->(_) { markup } })
    expect(body_text(doc)).to eq('a -> b')
  end

  it 'keeps the SVG through a template and in #markdown', if: Caracal::Md::Svg.embeddable? do
    docx = Caracal::Md.render('![Plan](plan.svg)', template: TemplateBuilder.build.to_s, image_loader: ->(_) { markup })
    expect_well_formed(docx)
    expect(picture_parts(docx).last).to include('<rect')
    expect(package(docx).default_content_type('svg')).to eq('image/svg+xml')

    document = Caracal::Document.new
    document.markdown '![Plan](plan.svg)', image_loader: ->(_) { markup }
    expect(picture_parts(document.render.string).last).to include('<rect')
  end

  it 'reads percent-encoded SVG data URIs' do
    uri = "data:image/svg+xml;utf8,#{URI::RFC2396_PARSER.escape(markup, /[^\w.~-]/)}"
    expect(Caracal::Md::ImageLoader.new.call(uri)).to eq(markup)
  end

  it 'gives Inkscape no file to read', if: system('command -v inkscape >/dev/null 2>&1') do
    Dir.mktmpdir do |dir|
      secret = File.join(dir, 'secret.png')
      File.binwrite(secret, png(60, 60))
      leaky = %(<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="100" height="100">) +
              %(<image width="60" height="60" xlink:href="file://#{secret}"/></svg>)
      inkscape = Caracal::Md::CommandHandler.new('inkscape --pipe --export-type=png --export-filename=-')
      block = ->(source) { Caracal::Md::CodeBlock.new(language: 'svg', source: source, attributes: {}) }

      leaked  = inkscape.call(block.call(leaky))
      cleaned = inkscape.call(block.call(Caracal::Md::Svg.clean(leaky).svg))
      empty   = inkscape.call(block.call(Caracal::Md::Svg.clean(leaky.sub(/<image.*?>/, '')).svg))
      expect(cleaned).to eq(empty)
      expect(leaked).not_to eq(empty)
    end
  end
end
